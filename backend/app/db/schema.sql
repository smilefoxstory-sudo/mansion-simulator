CREATE TABLE IF NOT EXISTS companies (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL
) DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  login_code VARCHAR(50) NOT NULL UNIQUE,
  role VARCHAR(20) NOT NULL,
  company_id INT NULL,
  display_name VARCHAR(100) NOT NULL,
  CONSTRAINT chk_users_role CHECK (role IN ('manager','bank')),
  FOREIGN KEY (company_id) REFERENCES companies(id)
) DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS cases (
  id INT AUTO_INCREMENT PRIMARY KEY,
  company_id INT NOT NULL,
  shared TINYINT(1) NOT NULL DEFAULT 0,
  name VARCHAR(100) NOT NULL,
  input_json LONGTEXT NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (company_id) REFERENCES companies(id)
) DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS predictions (
  id INT AUTO_INCREMENT PRIMARY KEY,
  case_id INT NOT NULL,
  judge VARCHAR(10) NOT NULL,
  deficit_year INT NULL,
  reserve_break_year INT NULL,
  shortage BIGINT NOT NULL,
  result_json LONGTEXT NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (case_id) REFERENCES cases(id) ON DELETE CASCADE
) DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS case_status (
  case_id INT PRIMARY KEY,
  status VARCHAR(30) NOT NULL DEFAULT '未対応',
  memo TEXT NULL,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (case_id) REFERENCES cases(id) ON DELETE CASCADE
) DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS plan_headers (
  id INT AUTO_INCREMENT PRIMARY KEY,
  case_id INT NOT NULL UNIQUE,
  title VARCHAR(100) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (case_id) REFERENCES cases(id) ON DELETE CASCADE
) DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS plan_works (
  id INT AUTO_INCREMENT PRIMARY KEY,
  plan_id INT NOT NULL,
  year INT NOT NULL,
  amount_gross BIGINT NOT NULL,
  note VARCHAR(200) NULL,
  FOREIGN KEY (plan_id) REFERENCES plan_headers(id) ON DELETE CASCADE
) DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS plan_fees (
  id INT AUTO_INCREMENT PRIMARY KEY,
  plan_id INT NOT NULL,
  from_year INT NOT NULL,
  fee BIGINT NOT NULL,
  FOREIGN KEY (plan_id) REFERENCES plan_headers(id) ON DELETE CASCADE
) DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS case_fees (
  case_id INT NOT NULL,
  from_year INT NOT NULL,
  fee BIGINT NOT NULL,
  PRIMARY KEY (case_id, from_year),
  FOREIGN KEY (case_id) REFERENCES cases(id) ON DELETE CASCADE
);